/// expenses/{expenseId} — a top-level collection (like [Patient]), scoped
/// by the same ownerId/ownerType pair. Unlike a patient's debt, an
/// expense's amountPaid/amountRemaining/paymentStatus mirror
/// [Order]'s pattern exactly (see order.dart): the client always writes
/// amountPaid: 0 at creation and lets an immediate recordPayment (if any)
/// go through the same onExpensePaymentCreated trigger that reconciles
/// later installments, rather than computing the split itself.
///
/// Deliberately independent of any patient data (no medical/PII fields at
/// all) — see the module's own note in the original spec: this is the one
/// piece of the clinic-management feature with no privacy/security
/// overlap with [Patient], so it can be built and shipped on its own.
@freezed
abstract class Expense with _$Expense {
  const factory Expense({
    required String id,
    required String ownerId,
    @Default(PatientOwnerType.doctor) String ownerType,
    required String description,
    @Default(ExpenseCategory.other) String category,
    @Default(ExpenseCostType.variable) String costType,
    @Default(false) bool isRecurringMonthly,
    // Set when this expense was auto-generated by generateRecurringExpenses
    // from an expenseTemplates/{id} doc; null for a one-off expense.
    String? templateId,
    // "YYYY-MM" — lets generateRecurringExpenses check idempotently
    // whether this month's instance of a template already exists.
    required String monthKey,
    required num totalAmount,
    @Default(0) num amountPaid,
    @Default(0) num amountRemaining,
    @Default('unpaid') String paymentStatus,
    @TimestampConverter() DateTime? expenseDate,
    required String createdByUid,
    @TimestampConverter() DateTime? createdAt,
  }) = _Expense;

  factory Expense.fromJson(Map<String, dynamic> json) =>
      _$ExpenseFromJson(json);

  factory Expense.fromDoc(String id, Map<String, dynamic> data) =>
      Expense.fromJson({...data, 'id': id});
}

class ExpenseCategory {
  ExpenseCategory._();

  static const rent = 'rent';
  static const salaries = 'salaries';
  static const bills = 'bills';
  static const nonMedicalSupplies = 'nonMedicalSupplies';
  static const maintenance = 'maintenance';
  static const marketing = 'marketing';
  static const other = 'other';

  static const all = [rent, salaries, bills, nonMedicalSupplies, maintenance, marketing, other];

  static const labels = {
    rent: 'إيجار',
    salaries: 'رواتب',
    bills: 'فواتير',
    nonMedicalSupplies: 'مستلزمات غير طبية',
    maintenance: 'صيانة',
    marketing: 'تسويق',
    other: 'أخرى',
  };
}

/// "تصنيف ثابت/متغير" — a simple visual distinction (not a financial
/// calculation) to help a doctor eyeball their monthly break-even point.
class ExpenseCostType {
  ExpenseCostType._();

  static const fixed = 'fixed';
  static const variable = 'variable';

  static const labels = {fixed: 'ثابت', variable: 'متغير'};
}

/// expenseTemplates/{templateId} — created alongside the first [Expense]
/// instance when a doctor checks "متكرر شهريًا"; generateRecurringExpenses
/// (Cloud Scheduler, monthly) then creates each following month's Expense
/// from this template with no further manual entry.
@freezed
abstract class ExpenseTemplate with _$ExpenseTemplate {
  const factory ExpenseTemplate({
    required String id,
    required String ownerId,
    @Default(PatientOwnerType.doctor) String ownerType,
    required String description,
    @Default(ExpenseCategory.other) String category,
    @Default(ExpenseCostType.fixed) String costType,
    required num amount,
    @Default(true) bool active,
    required String createdByUid,
    @TimestampConverter() DateTime? createdAt,
  }) = _ExpenseTemplate;

  factory ExpenseTemplate.fromJson(Map<String, dynamic> json) =>
      _$ExpenseTemplateFromJson(json);

  factory ExpenseTemplate.fromDoc(String id, Map<String, dynamic> data) =>
      ExpenseTemplate.fromJson({...data, 'id': id});
}

/// expenses/{expenseId}/payments/{paymentId} — append-only, identical
/// shape to [PatientPayment]/order.dart's Payment.
@freezed
abstract class ExpensePayment with _$ExpensePayment {
  const factory ExpensePayment({
    required String id,
    required num amount,
    @Default('cash') String method,
    required String recordedByUid,
    @TimestampConverter() DateTime? recordedAt,
    @Default('') String note,
  }) = _ExpensePayment;

  factory ExpensePayment.fromJson(Map<String, dynamic> json) =>
      _$ExpensePaymentFromJson(json);

  factory ExpensePayment.fromDoc(String id, Map<String, dynamic> data) =>
      ExpensePayment.fromJson({...data, 'id': id});
}
